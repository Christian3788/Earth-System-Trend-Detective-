function pointInPolygon(lon: number, lat: number, poly: LonLat[]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const xi = poly[i][0], yi = poly[i][1];
    const xj = poly[j][0], yj = poly[j][1];
    const intersect = yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi + 1e-12) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

export function computeIsLandRaw(lat: number, lon: number): boolean {
  let onLand = false;
  for (let p = 0; p < WORLD_LAND_POLYGONS.length; p++) {
    if (pointInPolygon(lon, lat, WORLD_LAND_POLYGONS[p])) {
      onLand = true;
      break;
    }
  }
  if (!onLand) return false;
  for (let w = 0; w < INLAND_WATER_POLYGONS.length; w++) {
    if (pointInPolygon(lon, lat, INLAND_WATER_POLYGONS[w])) {
      return false;
    }
  }
  return true;
}

// 360x180 land mask for fast 1-degree anomaly calculations
const LAND_MASK = new Uint8Array(360 * 180);
for (let y = 0; y < 180; y++) {
  const lat = 89.5 - y;
  for (let x = 0; x < 360; x++) {
    const lon = -179.5 + x;
    LAND_MASK[y * 360 + x] = computeIsLandRaw(lat, lon) ? 1 : 0;
  }
}

export function isLand(lat: number, lon: number): boolean {
  const clampedLat = Math.max(-89.5, Math.min(89.5, lat));
  const normLon = ((lon + 180) % 360 + 360) % 360 - 180;
  const y = Math.min(179, Math.max(0, Math.floor(89.5 - clampedLat + 0.5)));
  const x = Math.min(359, Math.max(0, Math.floor(normLon + 179.5 + 0.5)));
  return LAND_MASK[y * 360 + x] === 1;
}

export function getLandMaskBuffer(): Uint8Array {
  return LAND_MASK;
}

export function formatCoord(lat: number, lon: number): string {
  const latDir = lat >= 0 ? 'N' : 'S';
  const lonDir = lon >= 0 ? 'E' : 'W';
  return `${Math.abs(lat).toFixed(2)}° ${latDir}, ${Math.abs(lon).toFixed(2)}° ${lonDir}`;
}

export function getRegionName(lat: number, lon: number): string {
  const land = isLand(lat, lon);
  if (lat > 66.5) return land ? 'High Arctic Landmass' : 'Arctic Ocean Basin';
  if (lat < -60) return land ? 'Antarctic Ice Sheet' : 'Southern Ocean';

  if (land) {
    if (lon >= -170 && lon <= -52 && lat >= 15) return 'North America';
    if (lon >= -85 && lon <= -34 && lat < 15 && lat > -58) return 'South America';
    if (lon >= -12 && lon <= 40 && lat >= 35) return 'Europe';
    if (lon >= -20 && lon <= 52 && lat < 35 && lat >= -36) return 'Africa';
    if (lon > 40 && lon <= 180 && lat >= 5) return 'Asia';
    if (lon >= 110 && lon <= 180 && lat < -10) return 'Oceania / Australia';
    return 'Continental Landmass';
  }

  if (lon >= 32 && lon <= 43 && lat >= 12 && lat <= 30) return 'Red Sea';
  if (lon >= -6 && lon <= 36 && lat >= 30 && lat <= 45) return 'Mediterranean Sea';
  if (lon >= 20 && lon <= 120 && lat <= 30 && lat >= -45) {
    return lon < 75 ? 'Western Indian Ocean' : 'Eastern Indian Ocean';
  }
  if (lon >= -75 && lon < 20) {
    return lat >= 0 ? 'North Atlantic Ocean' : 'South Atlantic Ocean';
  }
  if (lat >= -15 && lat <= 15 && (lon > 120 || lon < -75)) {
    return lon >= -150 && lon < -75 ? 'Eastern Equatorial Pacific' : 'Western Equatorial Pacific';
  }
  return lat >= 0 ? 'North Pacific Ocean' : 'South Pacific Ocean';
}
